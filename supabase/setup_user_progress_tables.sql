-- User Progress Tables
-- Run this once in the Supabase SQL editor to set up cloud-based progress tracking
-- This enables progress to sync across devices when the same account is used

-- Table 1: Track which exercises have been completed by each user
create table if not exists public.user_exercise_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  exercise_id text not null,  -- internalId from curriculum (e.g., "CH01_EX01")
  completed_at timestamptz not null default now(),
  unique(user_id, exercise_id)  -- One record per user per exercise
);

alter table public.user_exercise_progress enable row level security;

-- RLS Policy: Users can only read their own exercise progress
create policy "Users can read their own exercise progress"
on public.user_exercise_progress for select
to authenticated
using (user_id = auth.uid());

-- RLS Policy: Users can only insert/update their own exercise progress
create policy "Users can insert their own exercise progress"
on public.user_exercise_progress for insert
to authenticated
with check (user_id = auth.uid());

create policy "Users can update their own exercise progress"
on public.user_exercise_progress for update
to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

create index if not exists user_exercise_progress_user_id_idx
on public.user_exercise_progress (user_id);

create index if not exists user_exercise_progress_user_exercise_idx
on public.user_exercise_progress (user_id, exercise_id);

---

-- Table 2: Track XP, streaks, and practice calendar for each user
create table if not exists public.user_gamification (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  total_xp int not null default 0,
  current_streak int not null default 0,
  longest_streak int not null default 0,
  practiced_dates text[] not null default '{}',  -- Array of 'yyyy-MM-dd' strings
  last_updated_at timestamptz not null default now()
);

alter table public.user_gamification enable row level security;

-- RLS Policy: Users can only read their own gamification data
create policy "Users can read their own gamification data"
on public.user_gamification for select
to authenticated
using (user_id = auth.uid());

-- RLS Policy: Users can only update their own gamification data (no direct insert needed)
create policy "Users can update their own gamification data"
on public.user_gamification for update
to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

create index if not exists user_gamification_user_id_idx
on public.user_gamification (user_id);

---

-- Table 3: Track practice activity (recording time, session count) for each user
create table if not exists public.user_practice_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  total_recorded_seconds int not null default 0,
  session_count int not null default 0,
  practice_dates text[] not null default '{}',  -- Array of 'yyyy-MM-dd' strings
  today_recorded_seconds int not null default 0,
  last_updated_at timestamptz not null default now()
);

alter table public.user_practice_activity enable row level security;

-- RLS Policy: Users can only read their own practice activity data
create policy "Users can read their own practice activity data"
on public.user_practice_activity for select
to authenticated
using (user_id = auth.uid());

-- RLS Policy: Users can only update their own practice activity data
create policy "Users can update their own practice activity data"
on public.user_practice_activity for update
to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

create index if not exists user_practice_activity_user_id_idx
on public.user_practice_activity (user_id);
