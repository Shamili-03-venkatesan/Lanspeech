-- Run once in the Supabase SQL editor before using the recording-analysis
-- feature. Creates a private Storage bucket for user recordings and scopes
-- access to each user's own folder (recordings/<their-auth-uid>/...),
-- matching the path SpeechAnalysisRepository uploads to.

insert into storage.buckets (id, name, public)
values ('speech-recordings', 'speech-recordings', false)
on conflict (id) do nothing;

drop policy if exists "Users can upload their own recordings"
on storage.objects;

create policy "Users can upload their own recordings"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'speech-recordings'
  and name like ('recordings/' || auth.uid()::text || '/%')
);

drop policy if exists "Users can read their own recordings"
on storage.objects;

create policy "Users can read their own recordings"
on storage.objects for select
to authenticated
using (
  bucket_id = 'speech-recordings'
  and name like ('recordings/' || auth.uid()::text || '/%')
);

create table if not exists public.speech_analyses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  exercise_id text not null,
  storage_path text not null,
  transcript text not null default '',
  speaking_duration_seconds numeric not null default 0,
  speaking_pace_wpm numeric not null default 0,
  pause_count integer not null default 0,
  hesitation_count integer not null default 0,
  fluency text not null,
  feedback text not null,
  created_at timestamptz not null default now()
);

alter table public.speech_analyses enable row level security;

drop policy if exists "Users can read their own speech analyses"
on public.speech_analyses;

create policy "Users can read their own speech analyses"
on public.speech_analyses for select
to authenticated
using (user_id = auth.uid());

create index if not exists speech_analyses_user_exercise_idx
on public.speech_analyses (user_id, exercise_id, created_at desc);

