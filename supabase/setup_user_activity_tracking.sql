-- User Activity Tracking

-- Tracks when each user was last active in the app

-- Run this once in the Supabase SQL editor to set up analytics

-- Table: Track last active timestamp for each user

create table if not exists public.user_activity (

  id bigint generated by default as identity primary key,

  user_id uuid not null unique references auth.users(id) on delete cascade,

  last_active_at timestamptz not null default now(),

  created_at timestamptz not null default now()

);

alter table public.user_activity enable row level security;

-- RLS Policy: Users can only read their own activity data

create policy "Users can read their own activity data"

on public.user_activity for select

to authenticated

using (user_id = auth.uid());

-- RLS Policy: Users can only update their own activity data

create policy "Users can update their own activity data"

on public.user_activity for update

to authenticated

using (user_id = auth.uid())

with check (user_id = auth.uid());

-- Index for efficient queries by user_id

create index if not exists user_activity_user_id_idx

on public.user_activity (user_id);