-- User Subscription / Premium Status

create table if not exists public.user_subscription (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  is_premium boolean not null default false,
  subscription_tier text not null default 'free',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Enable RLS
alter table public.user_subscription enable row level security;

-- Remove policy if it already exists
drop policy if exists "Users can read their own subscription data"
on public.user_subscription;

-- Users can only READ their own subscription
create policy "Users can read their own subscription data"
on public.user_subscription
for select
to authenticated
using (user_id = auth.uid());

-- IMPORTANT:
-- No INSERT / UPDATE / DELETE policies are created for normal users.
-- Premium status must be changed by a trusted backend/payment webhook.

-- Indexes
create index if not exists user_subscription_user_id_idx
on public.user_subscription (user_id);

create index if not exists user_subscription_is_premium_idx
on public.user_subscription (is_premium);